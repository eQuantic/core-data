using System.Collections;
using eQuantic.Core.Data.Modeling;
using eQuantic.Core.Data.Query;
using eQuantic.Core.Data.Relational;
using Npgsql;

namespace eQuantic.Core.Data.PostgreSql;

/// <summary>
///     PostgreSQL's SQL flavour: snake_case naming, <c>"quoted"</c> identifiers, <c>LIMIT/OFFSET</c>, identity
///     keys read back with <c>RETURNING</c>, native array columns (membership as <c>= ANY(col)</c>, atomic
///     append/remove), row-wise tuple comparisons, and scalar-keyed dictionaries as <c>jsonb</c> document
///     columns (<c>ContainsKey</c> as the <c>?</c> operator, indexer reads as <c>-&gt;&gt;</c>).
/// </summary>
public sealed class PostgreSqlDialect : SqlDialect
{
    /// <summary>Adds the PostgreSQL-specific function translations on top of the standard set.</summary>
    public PostgreSqlDialect() =>
        Functions.Map("get_Item", (column, arguments) => $"{column} ->> {arguments[0]}");

    /// <inheritdoc />
    public override string System => "postgresql";

    /// <inheritdoc />
    public override string Quote(string identifier) => "\"" + identifier.Replace("\"", "\"\"") + "\"";

    /// <inheritdoc />
    public override string GeneratedKeyDdl => "GENERATED BY DEFAULT AS IDENTITY";

    /// <inheritdoc />
    /// <remarks>
    ///     A PostgreSQL enum type: the data source maps the CLR enum onto it, so a parameter carries the label, and
    ///     the migrations create the type before a table uses it.
    /// </remarks>
    public override string EnumSqlType(RelationalNativeEnum declaration) => Quote(declaration.StoredName);

    /// <inheritdoc />
    public override bool EnumTypeRestrictsLabels => true;

    /// <inheritdoc />
    public override string ClockSql(Type type) => "now()";

    /// <inheritdoc />
    /// <remarks>
    ///     PostgreSQL has no <c>CREATE TYPE IF NOT EXISTS</c>; a type that is already there raises
    ///     <c>duplicate_object</c>, which the block swallows. Its labels are left as they are.
    /// </remarks>
    public override string? CreateEnumTypeSql(RelationalNativeEnum declaration) =>
        "DO $$ BEGIN CREATE TYPE " + Quote(declaration.StoredName) + " AS ENUM (" +
        string.Join(", ", declaration.Labels.Values.Select(label => "'" + label.Replace("'", "''") + "'")) +
        "); EXCEPTION WHEN duplicate_object THEN NULL; END $$";

    /// <inheritdoc />
    /// <remarks>
    ///     The data source read the catalogue when it opened its first connection, which may have been before the
    ///     migration created the type; until it reads it again, a native enum parameter has no type to go to.
    /// </remarks>
    public override Task ReloadTypesAsync(System.Data.Common.DbConnection connection, CancellationToken cancellationToken) =>
        ((NpgsqlConnection)connection).ReloadTypesAsync(cancellationToken);

    /// <inheritdoc />
    public override bool ReadsBackInsertedValues => true;

    /// <inheritdoc />
    public override string InsertSql(string quotedTable, string columns, string values, IReadOnlyList<string> returning,
        string? keyPredicate = null) =>
        returning.Count == 0
            ? $"INSERT INTO {quotedTable} ({columns}) VALUES ({values})"
            : $"INSERT INTO {quotedTable} ({columns}) VALUES ({values}) RETURNING {string.Join(", ", returning)}";

    /// <inheritdoc />
    /// <remarks>SQLSTATE <c>23505</c> (<c>unique_violation</c>), which names the constraint or index.</remarks>
    public override eQuantic.Core.Data.Repository.DuplicateKeyException? DuplicateKey(Exception exception) =>
        Find(exception) is { SqlState: PostgresErrorCodes.UniqueViolation } violation
            ? new eQuantic.Core.Data.Repository.DuplicateKeyException(violation.ConstraintName, exception)
            : null;

    /// <inheritdoc />
    public override bool IsDeadlock(Exception exception) =>
        Find(exception)?.SqlState is PostgresErrorCodes.DeadlockDetected or PostgresErrorCodes.SerializationFailure;

    private static PostgresException? Find(Exception? exception)
    {
        for (; exception is not null; exception = exception.InnerException)
        {
            if (exception is PostgresException postgres)
            {
                return postgres;
            }
        }

        return null;
    }

    /// <inheritdoc />
    /// <remarks>
    ///     <c>INSERT … ON CONFLICT (target) [WHERE predicate] DO UPDATE … RETURNING</c>: one statement, which PostgreSQL
    ///     runs without a race against any other upsert of the target, provided a unique index or constraint matches
    ///     it (the predicate infers a partial unique index; PostgreSQL refuses a target nothing holds unique).
    /// </remarks>
    public override bool UpsertsInOneStatement => true;

    /// <inheritdoc />
    public override string UpsertSql(string quotedTable, IReadOnlyList<string> insertColumns, IReadOnlyList<string> insertValues,
        IReadOnlyList<string> targetColumns, IReadOnlyList<string> targetValues, string? conflictFilter,
        IReadOnlyList<string> assignments, IReadOnlyList<string> returning) =>
        $"INSERT INTO {quotedTable} ({string.Join(", ", insertColumns)}) VALUES ({string.Join(", ", insertValues)}) " +
        $"ON CONFLICT ({string.Join(", ", targetColumns)})" + (conflictFilter is null ? string.Empty : $" WHERE {conflictFilter}") +
        $" DO UPDATE SET {string.Join(", ", assignments)} RETURNING {string.Join(", ", returning)}";

    /// <inheritdoc />
    /// <remarks><c>ON CONFLICT DO NOTHING</c> with no target leaves out a row that would take any unique key.</remarks>
    public override string? InsertSkippingDuplicatesSql(string quotedTable, string columns, IReadOnlyList<string> rows) =>
        $"WITH inserted AS (INSERT INTO {quotedTable} ({columns}) VALUES {string.Join(", ", rows)} " +
        "ON CONFLICT DO NOTHING RETURNING 1) SELECT count(*) FROM inserted";

    /// <inheritdoc />
    public override string? UpdateReturningSql(string quotedTable, string set, string where, IReadOnlyList<string> returning) =>
        $"UPDATE {quotedTable} SET {set} WHERE {where} RETURNING {string.Join(", ", returning)}";

    /// <inheritdoc />
    /// <remarks>
    ///     <c>format_type</c> quotes a type name that needs it (<c>"RunStatus"</c>) and leaves one that does not
    ///     (<c>run_status</c>), while the DDL always quotes it; the quotes are not part of the type.
    /// </remarks>
    public override string NormalizeStoredType(string storedType) =>
        base.NormalizeStoredType(storedType.Replace("\"", string.Empty));

    /// <inheritdoc />
    /// <remarks>
    ///     <c>format_type</c> is why this reads the catalogue directly instead of <c>information_schema</c>: it
    ///     returns the type exactly as PostgreSQL writes it, facets and array brackets included, which is the one
    ///     spelling a declared type can be compared against without reassembling it from parts.
    /// </remarks>
    public override string? IntrospectColumnsSql =>
        """
        SELECT c.relname, a.attname, format_type(a.atttypid, a.atttypmod), NOT a.attnotnull
        FROM pg_attribute a
        JOIN pg_class c ON c.oid = a.attrelid
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = current_schema() AND c.relkind = 'r' AND a.attnum > 0 AND NOT a.attisdropped
        """;

    /// <inheritdoc />
    protected override string Synonym(string baseType) => baseType switch
    {
        "character varying" => "varchar",
        "character" => "char",
        "timestamptz" => "timestamp with time zone",
        "timestamp" => "timestamp without time zone",
        "bool" => "boolean",
        "int2" => "smallint",
        "int4" => "integer",
        "int8" => "bigint",
        "float4" => "real",
        "float8" => "double precision",
        "decimal" => "numeric",
        _ => baseType,
    };

    /// <inheritdoc />
    public override string InsertSql(string quotedTable, string columns, string values, string? returningKey) =>
        returningKey is null
            ? $"INSERT INTO {quotedTable} ({columns}) VALUES ({values})"
            : $"INSERT INTO {quotedTable} ({columns}) VALUES ({values}) RETURNING {returningKey}";

    /// <inheritdoc />
    public override string CollectionContains(string column, string parameter, bool key) =>
        key
            ? $"{column} ? {parameter}"
            : $"{parameter} = ANY({column})";

    /// <inheritdoc />
    /// <remarks>
    ///     A scalar-keyed dictionary maps as a <c>jsonb</c> document column, and so does a JSON member
    ///     (<c>JsonDocument</c>, <c>JsonElement</c>, <c>JsonNode</c>), which holds any JSON: an object, an array or a scalar.
    /// </remarks>
    public override bool IsDocumentColumn(Type type)
    {
        if (base.IsDocumentColumn(type))
        {
            return true;
        }

        var dictionary = type.GetInterfaces().Append(type).FirstOrDefault(candidate =>
            candidate.IsGenericType && candidate.GetGenericTypeDefinition() == typeof(IDictionary<,>));
        return dictionary is not null && dictionary.GetGenericArguments()[0] == typeof(string);
    }

    /// <inheritdoc />
    /// <remarks>
    ///     Npgsql cannot infer <c>jsonb</c> for a dictionary value, and would send a JSON member as <c>json</c>;
    ///     the parameter is typed explicitly.
    /// </remarks>
    public override void ConfigureParameter(System.Data.Common.DbParameter parameter, object? value)
    {
        if ((value is IDictionary || JsonMembers.IsValue(value)) && parameter is Npgsql.NpgsqlParameter npgsql)
        {
            npgsql.DataTypeName = "jsonb";
        }
    }

    /// <inheritdoc />
    public override string TupleComparison(IReadOnlyList<string> columns, ComparisonOperator op, IReadOnlyList<string> parameters) =>
        $"({string.Join(", ", columns)}) {op switch
        {
            ComparisonOperator.Equal => "=",
            ComparisonOperator.NotEqual => "<>",
            ComparisonOperator.GreaterThan => ">",
            ComparisonOperator.GreaterThanOrEqual => ">=",
            ComparisonOperator.LessThan => "<",
            ComparisonOperator.LessThanOrEqual => "<=",
            _ => throw new NotSupportedException($"The operator '{op}' is not expressible."),
        }} ({string.Join(", ", parameters)})";

    /// <inheritdoc />
    public override string CollectionMutation(string column, string parameter, bool remove, bool prepend) => remove
        ? $"{column} = (SELECT COALESCE(array_agg(x), '{{}}') FROM unnest({column}) AS x WHERE x <> ALL({parameter}))"
        : prepend
            ? $"{column} = {parameter} || {column}"
            : $"{column} = {column} || {parameter}";

    /// <inheritdoc />
    public override string AlterColumnType(string quotedTable, string quotedColumn, string sqlType) =>
        $"ALTER TABLE {quotedTable} ALTER COLUMN {quotedColumn} TYPE {sqlType} USING {quotedColumn}::{sqlType}";

    /// <inheritdoc />
    public override string CreateIndexSql(string quotedName, string quotedTable, string columns, bool unique,
        eQuantic.Core.Data.Migration.IndexMethod method, string? filter)
    {
        if (method == eQuantic.Core.Data.Migration.IndexMethod.Gin)
        {
            if (unique)
            {
                throw new NotSupportedException("PostgreSQL GIN indexes cannot enforce uniqueness.");
            }

            return $"CREATE INDEX IF NOT EXISTS {quotedName} ON {quotedTable} USING GIN ({columns})"
                   + (filter is not null ? $" WHERE {filter}" : string.Empty);
        }

        return base.CreateIndexSql(quotedName, quotedTable, columns, unique, method, filter);
    }

    /// <inheritdoc />
    /// <remarks>
    ///     A GIN trigram index (<c>pg_trgm</c>): it serves <c>LIKE</c>/<c>ILIKE</c> with leading wildcards —
    ///     <c>Contains</c>/<c>EndsWith</c> stop scanning. The extension creation is idempotent and ships with
    ///     stock PostgreSQL; it does require the privilege to create extensions in the database.
    /// </remarks>
    public override IReadOnlyList<string> SearchIndexSql(string indexName, string quotedTable, string quotedColumn) =>
    [
        "CREATE EXTENSION IF NOT EXISTS pg_trgm",
        $"CREATE INDEX IF NOT EXISTS {Quote(indexName)} ON {quotedTable} USING GIN ({quotedColumn} gin_trgm_ops)",
    ];

    /// <inheritdoc />
    public override bool SupportsBulkInsert => true;

    /// <inheritdoc />
    /// <remarks>
    ///     PostgreSQL's binary <c>COPY</c> — the fastest load path the server offers: rows stream in the wire
    ///     format with no per-row statement, parse or plan. Npgsql infers each value's type from the CLR value,
    ///     which is why the engine hands over already-converted stored values.
    /// </remarks>
    public override async Task<long> BulkInsertAsync(System.Data.Common.DbConnection connection,
        System.Data.Common.DbTransaction? transaction, string quotedTable,
        IReadOnlyList<RelationalColumn> columns, IReadOnlyList<object?[]> rows, CancellationToken cancellationToken)
    {
        var target = $"{quotedTable} ({string.Join(", ", columns.Select(column => Quote(column.Name)))})";
        var npgsql = (NpgsqlConnection)connection;

        await using var writer = await npgsql.BeginBinaryImportAsync(
            $"COPY {target} FROM STDIN (FORMAT BINARY)", cancellationToken).ConfigureAwait(false);

        foreach (var row in rows)
        {
            await writer.StartRowAsync(cancellationToken).ConfigureAwait(false);
            foreach (var value in row)
            {
                if (value is null)
                {
                    await writer.WriteNullAsync(cancellationToken).ConfigureAwait(false);
                }
                else
                {
                    await writer.WriteAsync(value, cancellationToken).ConfigureAwait(false);
                }
            }
        }

        return (long)await writer.CompleteAsync(cancellationToken).ConfigureAwait(false);
    }

    /// <inheritdoc />
    public override string AddColumnSql(string quotedTable, string quotedColumn, string sqlType) =>
        $"ALTER TABLE {quotedTable} ADD COLUMN IF NOT EXISTS {quotedColumn} {sqlType}";

    /// <inheritdoc />
    public override string DropColumnSql(string quotedTable, string quotedColumn) =>
        $"ALTER TABLE {quotedTable} DROP COLUMN IF EXISTS {quotedColumn}";

    /// <inheritdoc />
    public override string SqlType(Type type)
    {
        var underlying = Nullable.GetUnderlyingType(type) ?? type;

        if (underlying.IsEnum)
        {
            return NativeEnumOf(underlying) is { } native ? EnumSqlType(native) : "integer";
        }

        // Dictionaries are documents, not arrays — checked before the IEnumerable branch.
        if (IsDocumentColumn(underlying))
        {
            return "jsonb";
        }

        if (underlying != typeof(string) && underlying != typeof(byte[]))
        {
            if (underlying.IsArray)
            {
                return SqlType(underlying.GetElementType()!) + "[]";
            }

            var element = underlying.GetInterfaces().Append(underlying)
                .FirstOrDefault(candidate => candidate.IsGenericType && candidate.GetGenericTypeDefinition() == typeof(IEnumerable<>))
                ?.GetGenericArguments()[0];
            if (element is not null)
            {
                return SqlType(element) + "[]";
            }
        }

        return underlying switch
        {
            _ when underlying == typeof(string) => "text",
            _ when underlying == typeof(Guid) => "uuid",
            _ when underlying == typeof(bool) => "boolean",
            _ when underlying == typeof(byte) || underlying == typeof(short) => "smallint",
            _ when underlying == typeof(int) => "integer",
            _ when underlying == typeof(long) => "bigint",
            _ when underlying == typeof(float) => "real",
            _ when underlying == typeof(double) => "double precision",
            _ when underlying == typeof(decimal) => "numeric",
            _ when underlying == typeof(DateTime) || underlying == typeof(DateTimeOffset) => "timestamp with time zone",
            _ when underlying == typeof(TimeSpan) => "interval",
            _ when underlying == typeof(byte[]) => "bytea",
            _ => throw new NotSupportedException($"No PostgreSQL type mapping for '{underlying.Name}'."),
        };
    }

    /// <inheritdoc />
    public override object? BindValue(object? value) => value switch
    {
        // timestamptz demands a UTC kind; an Unspecified value is taken as UTC (matching the storage semantics).
        DateTime { Kind: DateTimeKind.Unspecified } dateTime => DateTime.SpecifyKind(dateTime, DateTimeKind.Utc),
        // An enum stored as its labels goes as itself: the data source maps it to its PostgreSQL type and sends
        // the label. A JSON member goes as itself too, into a jsonb parameter (ConfigureParameter).
        Enum enumValue when NativeEnumOf(enumValue.GetType()) is not null => value,
        Enum enumValue => Convert.ToInt32(enumValue),
        _ when JsonMembers.IsValue(value) => value,
        _ => value,
    };
}
