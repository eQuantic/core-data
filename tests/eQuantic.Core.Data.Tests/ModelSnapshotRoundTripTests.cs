using System.Reflection;
using eQuantic.Core.Data.Evolution;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace eQuantic.Core.Data.Tests;

/// <summary>
///     A snapshot is read back by compiling the file it was written as, the way the application's build does, so
///     that is how these tests read it. Two promises are held here: what is written reads back as the model it
///     described, the stored form and the generation included; and a file written before the generation was
///     recorded still compiles, and still compares as it did.
/// </summary>
[TestFixture]
public sealed class ModelSnapshotRoundTripTests
{
    /// <summary>A snapshot file exactly as the tooling wrote one before it recorded generation or labels.</summary>
    private const string WrittenBeforeGeneration =
        """
        // <auto-generated />
        // The model as it stood when the last change was generated. Regenerated by the tooling;
        // edit the model, not this file.
        #nullable enable

        using eQuantic.Core.Data.Evolution;

        namespace Shop.Migrations;

        public sealed class DataModelSnapshot : IModelSnapshotFile
        {
            /// <inheritdoc />
            public ModelSnapshot Model => new(
                "postgresql",
                [
                    new EntitySnapshot("Shop.Order", "orders",
                        [
                            new FieldSnapshot("Id", "id", "System.Guid"),
                            new FieldSnapshot("Number", "number", "System.Int64"),
                            new FieldSnapshot("State", "state", "Shop.OrderState"),
                            new FieldSnapshot("Total", "total", "System.Decimal") { Precision = 18, Scale = 2 },
                        ])
                    {
                        Keys = ["Id"],
                    },
                ]);
        }
        """;

    private static ModelSnapshot Load(string source)
    {
        // The application's own references: the runtime, and the assembly that defines the snapshot types.
        var references = ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!)
            .Split(Path.PathSeparator)
            .Append(typeof(ModelSnapshot).Assembly.Location)
            .GroupBy(Path.GetFileName, StringComparer.OrdinalIgnoreCase)
            .Select(paths => MetadataReference.CreateFromFile(paths.First()));

        var compilation = CSharpCompilation.Create("Snapshot_" + Guid.NewGuid().ToString("N"),
            [CSharpSyntaxTree.ParseText(source, new CSharpParseOptions(LanguageVersion.CSharp12))],
            references,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary,
                nullableContextOptions: NullableContextOptions.Enable));

        using var image = new MemoryStream();
        var result = compilation.Emit(image);
        Assert.That(result.Success, Is.True, string.Join(Environment.NewLine,
            result.Diagnostics.Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error)));

        var assembly = Assembly.Load(image.ToArray());
        var type = assembly.GetTypes().Single(candidate => typeof(IModelSnapshotFile).IsAssignableFrom(candidate));
        return ((IModelSnapshotFile)Activator.CreateInstance(type)!).Model;
    }

    private static ModelSnapshot Current(string? numberGenerated = null, string stateType = "Shop.OrderState") =>
        new("postgresql",
        [
            new EntitySnapshot("Shop.Order", "orders",
            [
                new FieldSnapshot("Id", "id", "System.Guid"),
                new FieldSnapshot("Number", "number", "System.Int64") { Generated = numberGenerated },
                new FieldSnapshot("State", "state", stateType),
                new FieldSnapshot("Total", "total", "System.Decimal") { Precision = 18, Scale = 2 },
            ]) { Keys = ["Id"] },
        ]);

    [Test]
    public void A_written_snapshot_reads_back_as_the_model_it_describes()
    {
        var model = new ModelSnapshot("postgresql",
        [
            new EntitySnapshot("Shop.Order", "orders",
            [
                new FieldSnapshot("At", "at", "System.DateTime") { Generated = "default now()" },
                new FieldSnapshot("History", "history", "labels:Shop.OrderState[]") { Nullable = true },
                new FieldSnapshot("Id", "id", "System.Guid"),
                new FieldSnapshot("Number", "number", "System.Int64") { Generated = "sequence" },
                new FieldSnapshot("Stamp", "stamp", "System.DateTimeOffset") { Generated = "clock" },
                new FieldSnapshot("State", "state", "labels:Shop.OrderState")
                {
                    Labels = [new("Queued", 0, "queued"), new("InProgress", 1, "in_progress"), new("Large", -3000000000, "large")],
                },
            ]) { Keys = ["Id"], KeyIsGenerated = true },
        ]);
        var written = ModelSnapshotWriter.Write(model, "Shop.Migrations");

        var read = Load(written);

        Assert.That(ModelDiffer.Compare(read, model).IsEmpty, Is.True, "nothing the model holds is lost on the way");
        Assert.That(read.For("Shop.Order")!.Field("Number")!.Generated, Is.EqualTo("sequence"));
        Assert.That(read.For("Shop.Order")!.Field("At")!.Generated, Is.EqualTo("default now()"));
        Assert.That(read.For("Shop.Order")!.Field("State")!.StoredType, Is.EqualTo("labels:Shop.OrderState"));
        Assert.That(read.For("Shop.Order")!.Field("State")!.Labels,
            Is.EqualTo(model.For("Shop.Order")!.Field("State")!.Labels), "every label, its member and its number");
        Assert.That(ModelSnapshotWriter.Write(read, "Shop.Migrations"), Is.EqualTo(written),
            "written again, it is the same file");
    }

    [Test]
    public void The_written_file_carries_the_generation_only_where_there_is_one()
    {
        var written = ModelSnapshotWriter.Write(Current(numberGenerated: "sequence"), "Shop.Migrations");

        Assert.That(written, Does.Contain(
            "new FieldSnapshot(\"Number\", \"number\", \"System.Int64\") { Generated = \"sequence\" }"));
        Assert.That(written, Does.Contain("new FieldSnapshot(\"Id\", \"id\", \"System.Guid\"),"),
            "a member the application writes is written as it always was");
    }

    [Test]
    public void A_model_without_generation_or_labels_writes_the_file_it_wrote_before()
    {
        Assert.That(ModelSnapshotWriter.Write(Current(), "Shop.Migrations").ReplaceLineEndings(),
            Is.EqualTo(WrittenBeforeGeneration.ReplaceLineEndings() + Environment.NewLine),
            "regenerating an unchanged model must not show up as a change in review");
    }

    [Test]
    public void A_snapshot_written_before_generation_was_recorded_still_reads_and_compares_clean()
    {
        var old = Load(WrittenBeforeGeneration);

        Assert.That(old.For("Shop.Order")!.Fields.Select(field => field.Generated), Is.All.Null);
        Assert.That(ModelDiffer.Compare(old, Current()).IsEmpty, Is.True,
            "a model that did not move must not read as moved because the file is older than the property");
    }

    [Test]
    public void Against_a_snapshot_written_before_it_a_member_made_store_generated_is_the_one_change()
    {
        var change = ModelDiffer.Compare(Load(WrittenBeforeGeneration), Current(numberGenerated: "sequence"))
            .Changes.Single();

        Assert.That(change.Kind, Is.EqualTo(ModelChangeKind.ChangeGeneration));
        Assert.That(change.Member, Is.EqualTo("Number"));
    }

    [Test]
    public void Against_a_snapshot_written_before_it_an_enum_switched_to_labels_is_a_conversion_handed_back()
    {
        var difference = ModelDiffer.Compare(Load(WrittenBeforeGeneration),
            Current(stateType: "labels:Shop.OrderState"));

        var change = difference.Changes.Single();
        Assert.That(change.Kind, Is.EqualTo(ModelChangeKind.ConvertField));
        var migration = MigrationWriter.Write(difference, "Labels", "Shop.Migrations", new DateTime(2026, 11, 13));
        Assert.That(migration, Does.Not.Contain(".ConvertField("));
        Assert.That(migration, Does.Contain("#error 'Shop.Order.State' is now stored as the labels of Shop.OrderState"));
    }
}
